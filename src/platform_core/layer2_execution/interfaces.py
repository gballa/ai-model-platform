from __future__ import annotations
from typing import Protocol, Any, Dict, Union

class AbstractExecutionContext(Protocol):
    """Abstract interface for execution environment (e.g., sandbox)."""
    def provision_microvm(self, vm_id: str, initial_files: Dict[str, Union[str, bytes]] = None, tainted: bool = True) -> Dict[str, Any]: ...
    def create_cow_snapshot(self, vm_id: str) -> Any: ...
    def restore_cow_snapshot(self, snapshot_id: str) -> Dict[str, Any]: ...
    def execute_python_in_sandbox(self, vm_id: str, python_code: str, timeout_sec: float = 10.0) -> Any: ...
    def check_network_egress(self, vm_id: str, destination: str) -> Any: ...
